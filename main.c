/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_ADC1_Init();
  MX_TIM1_Init();
  /* USER CODE BEGIN 2 */

  // 1. MUST calibrate the Blue Pill ADC before using it!
  HAL_ADCEx_Calibration_Start(&hadc1);
  // 2. Power on the ADC permanently
  HAL_ADC_Start(&hadc1);

  // 3. Enable Timer 1 Output Compare Preload on CH1
  htim1.Instance->CCMR1 |= TIM_CCMR1_OC1PE;
  htim1.Instance->CR1   |= TIM_CR1_ARPE;

  // 4. Start PWM and Control Loop Interrupt (runs at 35 kHz)
  HAL_TIM_PWM_Start(&htim1, TIM_CHANNEL_1);
  HAL_TIM_Base_Start_IT(&htim1);

  // Record the initial timestamp for the FSM
  last_step_time = HAL_GetTick();
  uint32_t last_led_time = HAL_GetTick();

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */

	// --- The PC13 Heartbeat LED (Blinks every 2000ms) ---
    if ((HAL_GetTick() - last_led_time) >= 2000)
    {
        last_led_time = HAL_GetTick();
        HAL_GPIO_TogglePin(GPIOC, GPIO_PIN_13);
    }
	
    if ((HAL_GetTick() - last_step_time) >= STEP_DELAY_MS) 
    {
        last_step_time = HAL_GetTick();
        
        switch (current_state) 
		{
    		case 0: target_voltage = 10.0f; break;
   	 		case 1: target_voltage = 9.00f;  break;
    		case 2: target_voltage = 6.00f;  break;
    		case 3: target_voltage = 3.00f;  break;
		}
        current_state = (current_state + 1) % 4;
    }
  }
  /* USER CODE END 3 */
}

