/* USER CODE BEGIN 4 */
void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim) 
{
    // Check to ensure Timer 1 triggered the interrupt
    if (htim->Instance == TIM1) 
    {
        // Read ADC
        raw_adc = ADC1->DR;
        
        // Measured volts (4x divider: 3.3V * 4 = 13.2V )
        float measured_volts = ((float)raw_adc / 4095.0f) * 13.2f;
        
        // Error
        float error = target_voltage - measured_volts;
        integral_sum += error;
        
        float duty_ff = target_voltage / 12.0f; 
        float duty_cycle = duty_ff + (Kp * error) + (Ki * integral_sum);
		// float duty_cycle = 0.20f;
        // Clamping (5% to 92%)
        if (duty_cycle > 0.92f) {
            duty_cycle = 0.92f;
            integral_sum -= error;
        } 
        else if (duty_cycle < 0.05f) {
            duty_cycle = 0.05f;
            integral_sum -= error;
        }
        
        // Write directly to CCR1
        TIM1->CCR1 = (uint32_t)(duty_cycle * 1828.0f);
        
        // Trigger next ADC
        ADC1->CR2 |= ADC_CR2_SWSTART;

    }
}
